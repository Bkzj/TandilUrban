/**
 * Escapes untrusted plain text for insertion into HTML text or quoted
 * attribute values. Input is always text, never pre-sanitized HTML.
 */
export function escapePlainTextForHtml(value: string): string {
  return value.replace(/[&<>"']/gu, (character) => {
    switch (character) {
      case '&':
        return '&amp;';
      case '<':
        return '&lt;';
      case '>':
        return '&gt;';
      case '"':
        return '&quot;';
      case "'":
        return '&#39;';
      default:
        return character;
    }
  });
}
